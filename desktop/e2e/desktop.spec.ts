import { test, expect, _electron as electron } from '@playwright/test'
import { mkdtemp, rm, readFile, writeFile, realpath } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { execFileSync } from 'node:child_process'

test('desktop lifecycle, streaming, control, font loading and exit confirmation', async () => {
  const repository = resolve('..')
  const root = await mkdtemp(join(tmpdir(), 'palette-desktop-'))
  const uv = process.env.PALETTE_UV ?? 'uv'
  execFileSync(uv, ['run', 'python', resolve('scripts/setup_fixture.py'), root], { cwd: repository })
  const application = await electron.launch({ args: [resolve('out/main/index.js')], env: { ...process.env, PALETTE_ROOT: root, PALETTE_UV: uv } })
  try {
    const page = await application.firstWindow()
    // On macOS the DOM fullscreen event precedes the native window transition.
    async function transitionFullscreen(event: 'enter-full-screen' | 'leave-full-screen', action: () => Promise<unknown>): Promise<void> {
      await application.evaluate(({ BrowserWindow }, event) => {
        const state = globalThis as typeof globalThis & { fullscreenTransition?: Promise<void> }
        state.fullscreenTransition = new Promise((resolve, reject) => {
          const window = BrowserWindow.getAllWindows()[0]
          const complete = (): void => { clearTimeout(timeout); resolve() }
          const timeout = setTimeout(() => { window.removeListener(event, complete); reject(new Error(`Native fullscreen transition timed out: ${event}`)) }, 10_000)
          window.once(event, complete)
        })
      }, event)
      await action()
      await application.evaluate(() => (globalThis as typeof globalThis & { fullscreenTransition?: Promise<void> }).fullscreenTransition)
    }
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await expect(page.getByText('后台已连接')).toBeVisible({ timeout: 30_000 })
    await expect(page.getByRole('heading', { name: '还没有虚拟机' })).toBeVisible()
    await page.evaluate(async () => { await document.fonts.ready })
    await page.screenshot({ path: 'test-results/workspace-empty.png' })
    await page.getByRole('button', { name: '收起侧栏' }).click()
    await expect(page.locator('.app-sidebar')).toBeHidden()
    await page.getByRole('button', { name: '展开侧栏' }).click()
    await expect(page.locator('.app-sidebar')).toBeVisible()
    await page.getByRole('button', { name: '从 ISO 安装', exact: false }).click()
    await expect(page.getByRole('dialog').getByLabel('ISO 文件')).toBeVisible()
    await page.getByRole('button', { name: '取消', exact: true }).click()
    await application.evaluate(({ dialog }, path) => {
      dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] })
    }, join(root, 'base.qcow2'))
    await page.getByRole('button', { name: '创建虚拟机', exact: true }).first().click()
    const wizard = page.getByRole('dialog')
    await wizard.getByRole('button', { name: '浏览', exact: true }).click()
    await expect(wizard.getByLabel('镜像文件')).toHaveValue(join(root, 'base.qcow2'))
    await wizard.getByRole('button', { name: '下一步', exact: true }).click()
    await wizard.getByLabel('名称', { exact: true }).fill('开发环境')
    await wizard.getByLabel('CPU 核数').fill('1')
    await wizard.getByLabel('内存 / GiB').fill('0.5')
    await wizard.getByLabel('磁盘 / GiB').fill('24')
    await wizard.getByLabel('网络', { exact: true }).selectOption('offline')
    await wizard.getByRole('button', { name: '更多硬件选项', exact: true }).click()
    await expect(wizard.getByLabel('虚拟显卡')).toHaveValue('VGA')
    await wizard.getByRole('button', { name: '声音', exact: true }).click()
    await expect(wizard.getByLabel('声音输出')).toHaveValue('disabled')
    await wizard.getByRole('button', { name: '收起硬件选项', exact: true }).click()
    await page.screenshot({ path: 'test-results/create-configuration.png' })
    await wizard.getByRole('button', { name: '下一步', exact: true }).click()
    await expect(wizard.getByRole('heading', { name: '确认创建' })).toBeVisible()
    await wizard.getByRole('button', { name: '创建虚拟机', exact: true }).click()
    await expect(page.getByRole('button', { name: '开发环境' }).first()).toBeVisible({ timeout: 10_000 })
    await page.getByRole('button', { name: '开发环境' }).first().click()
    await page.getByRole('button', { name: '启动', exact: true }).click()
    await expect(page.getByText('仅查看', { exact: true })).toBeVisible({ timeout: 20_000 })
    const guestCanvas = page.getByRole('tabpanel', { name: '控制台' }).locator('canvas')
    await expect(guestCanvas).toBeVisible()
    expect(await guestCanvas.evaluate((canvas: HTMLCanvasElement) => ({ width: canvas.width, height: canvas.height }))).toEqual({ width: 320, height: 200 })
    const identity = await page.evaluate(async () => {
      const { vms } = await window.palette.request('vms.list') as { vms: { vm_id: string; status: { action_seq: number } }[] }
      return vms[0]
    })
    const evidence = join(root, 'mcp-evidence')
    execFileSync(uv, ['run', 'python', join(repository, 'scripts/mcp_click_test.py'), '--root', root, '--vm-id', identity.vm_id, '--x', '20', '--y', '20', '--out', evidence], { cwd: repository })
    const report = JSON.parse(await readFile(join(evidence, 'report.json'), 'utf8'))
    expect(report.ok).toBe(true)
    await page.getByRole('tab', { name: '状态', exact: true }).click()
    await expect(page.getByTestId('action-seq')).toHaveText(String(identity.status.action_seq + 1), { timeout: 10_000 })
    await expect(page.getByTestId('control-owner')).toHaveText('Agent / 可操作')
    await expect(page.getByTestId('held-keys')).toHaveText('无')
    await page.screenshot({ path: 'test-results/mcp-live-status.png' })
    await page.getByRole('tab', { name: '控制台', exact: true }).click()
    await expect(page.getByText('仅查看', { exact: true })).toBeVisible({ timeout: 10_000 })
    await page.getByRole('button', { name: '接管', exact: true }).click()
    await expect(page.getByText('人工控制', { exact: true })).toBeVisible()
    const blockedEvidence = join(root, 'mcp-blocked')
    execFileSync(uv, ['run', 'python', join(repository, 'scripts/mcp_click_test.py'), '--root', root, '--vm-id', identity.vm_id, '--x', '20', '--y', '20', '--expect-error', 'BUSY', '--out', blockedEvidence], { cwd: repository })
    const blockedReport = JSON.parse(await readFile(join(blockedEvidence, 'report.json'), 'utf8'))
    expect(blockedReport.ok).toBe(true)
    expect(blockedReport.expected_error).toBe('BUSY')
    await page.keyboard.down('a')
    await expect.poll(async () => page.evaluate(async () => (await window.palette.request('vms.list') as { vms: { status: { input_ledger: { keys: string[] } } }[] }).vms[0].status.input_ledger.keys)).toContain('a')
    await page.keyboard.up('a')
    await expect.poll(async () => page.evaluate(async () => (await window.palette.request('vms.list') as { vms: { status: { input_ledger: { keys: string[] } } }[] }).vms[0].status.input_ledger.keys)).toEqual([])
    await page.getByRole('button', { name: '交还 Agent' }).click()
    await expect(page.getByText('仅查看', { exact: true })).toBeVisible()
    await transitionFullscreen('enter-full-screen', () => page.getByRole('button', { name: '全屏', exact: true }).click())
    await expect.poll(() => page.evaluate(() => !!document.fullscreenElement)).toBe(true)
    await transitionFullscreen('leave-full-screen', () => page.getByRole('button', { name: '退出全屏', exact: true }).click())
    await expect.poll(() => page.evaluate(() => !!document.fullscreenElement)).toBe(false)
    await expect(page.getByRole('button', { name: '全屏', exact: true })).toHaveAttribute('aria-pressed', 'false')
    await transitionFullscreen('enter-full-screen', () => page.getByRole('button', { name: '全屏', exact: true }).click())
    await expect.poll(() => page.evaluate(() => !!document.fullscreenElement)).toBe(true)
    await transitionFullscreen('leave-full-screen', () => page.keyboard.press('Escape'))
    await expect.poll(() => page.evaluate(() => !!document.fullscreenElement)).toBe(false)
    await expect(page.getByRole('button', { name: '全屏', exact: true })).toBeVisible()
    await page.getByLabel('开发环境 的操作').selectOption('stop')
    await expect(page.getByRole('button', { name: '启动', exact: true })).toBeVisible({ timeout: 10_000 })
    await page.getByRole('button', { name: '启动', exact: true }).click()
    await expect(page.getByText('仅查看', { exact: true })).toBeVisible({ timeout: 20_000 })
    await page.evaluate(async () => { await document.fonts.ready })
    expect(await page.locator('h1').evaluate(element => getComputedStyle(element).fontFamily)).toContain('Inter')
    expect(await page.locator('body').innerText()).not.toMatch(/prompt|Cashmere|Electron|TypeScript|生成|设计系统/i)
    await page.screenshot({ path: 'test-results/console-1440.png' })
    await page.getByRole('button', { name: '返回虚拟机列表' }).click()
    await page.getByLabel('搜索虚拟机').fill('不存在的虚拟机')
    await expect(page.getByText('没有匹配的虚拟机', { exact: true })).toBeVisible()
    await page.getByLabel('搜索虚拟机').fill('')
    await expect(page.locator('tbody').getByRole('button', { name: '开发环境' })).toBeVisible()
    await page.getByRole('button', { name: '环境设置', exact: true }).click()
    await expect(page.getByRole('heading', { name: '环境设置' })).toBeVisible()
    await expect(page.getByText(await realpath(root), { exact: true })).toBeVisible()
    await page.screenshot({ path: 'test-results/settings-1440.png' })
    await page.getByRole('button', { name: '全部虚拟机', exact: true }).click()
    const capture = await readFile(resolve('scripts/capture-spacing.js'), 'utf8')
    const states: unknown[] = []
    for (const width of [1440, 1728, 390]) {
      await application.evaluate(({ BrowserWindow }, width) => { const window = BrowserWindow.getAllWindows()[0]; window.setMinimumSize(390, 640); window.setContentSize(width, width === 390 ? 844 : 900) }, width)
      await page.waitForFunction(width => window.innerWidth === width, width)
      states.push(await page.evaluate(capture))
      await page.screenshot({ path: `test-results/vms-${width}.png` })
    }
    await writeFile(resolve('test-results/spacing.json'), JSON.stringify(states))
    await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close())
    await expect(page.getByRole('heading', { name: '虚拟机仍在运行' })).toBeVisible()
    await page.getByRole('button', { name: '取消', exact: true }).click()
    expect(errors).toEqual([])
  } finally {
    await application.evaluate(({ app }) => app.exit(0)).catch(() => {})
    await application.close().catch(() => {})
    try { execFileSync(uv, ['run', 'palette', '--root', root, 'daemon', 'stop'], { cwd: repository }) } catch { /* Test cleanup may have stopped it already. */ }
    await new Promise(resolve => setTimeout(resolve, 500))
    await rm(root, { recursive: true, force: true, maxRetries: 20, retryDelay: 250 })
  }
})
