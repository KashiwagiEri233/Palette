import { test, expect, _electron as electron } from '@playwright/test'
import { mkdtemp, rm, writeFile, readFile, access } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { execFileSync } from 'node:child_process'
import type { VmSettingsResult } from '../src/shared/types'

test('UTM drive creation imports owned copies, selects interfaces and preserves staged edits', async () => {
  test.setTimeout(120000)
  const repository = resolve('..')
  const root = await mkdtemp(join(tmpdir(), 'palette-devices-'))
  const uv = process.env.PALETTE_UV ?? 'uv'
  execFileSync(uv, ['run', 'python', resolve('scripts/setup_fixture.py'), root], { cwd: repository })
  const iso = join(root, 'cn_windows_8.1_enterprise_with_update_x64_dvd_long_filename.iso')
  await writeFile(iso, 'external ISO')
  const base = join(root, 'base.qcow2')
  const original = await readFile(base)
  const app = await electron.launch({ args: [resolve('out/main/index.js')], env: { ...process.env, PALETTE_ROOT: root, PALETTE_UV: uv } })
  try {
    const page = await app.firstWindow()
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await expect(page.getByText('后台已连接')).toBeVisible({ timeout: 30000 })
    const vmId = await page.evaluate(async path => (await window.palette.request('vms.create', undefined, { name: 'UTM 磁盘管理', profile_id: 'default', source: 'image', path, vcpus: 1, memory_mib: 512, disk_gib: 24, network: 'offline' }) as { vm_id: string }).vm_id, base)
    const data = () => page.evaluate(async id => window.palette.request('vms.settings.get', id) as Promise<VmSettingsResult>, vmId)
    await page.getByRole('button', { name: '虚拟机管理', exact: true }).click()
    await page.getByRole('button', { name: 'UTM 磁盘管理', exact: true }).click()
    const settings = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: '虚拟机设置', exact: true }) })
    const create = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: '新建驱动器', exact: true }) })
    const nav = settings.getByRole('navigation', { name: '设置分类' })
    const open = async () => { await page.getByRole('button', { name: '虚拟机设置', exact: true }).click(); await expect(nav).toBeVisible() }
    const newDrive = async () => { await nav.getByRole('button', { name: '新建驱动器', exact: true }).click(); await expect(create).toBeVisible() }
    await open(); await newDrive()
    await create.getByRole('button', { name: '取消', exact: true }).click()
    await expect(nav.locator('[data-drive-id]')).toHaveCount(1)
    await newDrive()
    await create.getByLabel('容量 / GiB').fill('2')
    await create.getByRole('combobox', { name: '接口', exact: true }).click()
    await page.getByRole('option', { name: 'IDE', exact: true }).click()
    await create.getByRole('combobox', { name: '镜像格式', exact: true }).click()
    await page.getByRole('option', { name: 'RAW', exact: true }).click()
    await page.screenshot({ path: 'test-results/utm-new-drive.png', animations: 'disabled' })
    await create.getByRole('button', { name: '创建', exact: true }).click()
    await expect(settings.getByRole('heading', { name: 'IDE 磁盘 1', exact: true })).toBeVisible()
    expect((await data()).managed_disks!['drive-primary'].allocated).toBe(false)
    await newDrive()
    await create.getByRole('checkbox', { name: '可移动介质' }).check()
    await create.getByRole('button', { name: '创建', exact: true }).click()
    await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }) }, iso)
    await settings.getByRole('button', { name: '浏览…', exact: true }).click()
    await expect(settings.getByLabel('介质文件', { exact: true })).toHaveValue(iso)
    await page.screenshot({ path: 'test-results/utm-drive-long-filename.png', animations: 'disabled' })
    const opticalActions = nav.getByRole('button', { name: 'USB 光驱 1 的操作', exact: true })
    const actionBounds = await opticalActions.boundingBox()
    expect(actionBounds).not.toBeNull()
    expect(actionBounds!.width).toBe(actionBounds!.height)
    await opticalActions.hover()
    await page.screenshot({ path: 'test-results/utm-drive-actions-hover.png', animations: 'disabled' })
    await opticalActions.click()
    await expect(page.getByRole('menuitem', { name: '删除驱动器…', exact: true })).toBeVisible()
    expect(await opticalActions.boundingBox()).toEqual(actionBounds)
    await page.screenshot({ path: 'test-results/utm-drive-actions-open.png', animations: 'disabled' })
    await page.keyboard.press('Escape')
    await nav.getByRole('button', { name: '常规', exact: true }).click()
    const unselectedBounds = await opticalActions.boundingBox()
    await opticalActions.click()
    await expect(page.getByRole('menuitem', { name: '删除驱动器…', exact: true })).toBeVisible()
    expect(await opticalActions.boundingBox()).toEqual(unselectedBounds)
    await page.screenshot({ path: 'test-results/utm-drive-actions-unselected.png', animations: 'disabled' })
    await page.keyboard.press('Escape')
    await newDrive()
    await app.evaluate(({ dialog }) => { dialog.showOpenDialog = async () => ({ canceled: true, filePaths: [] }) })
    await create.getByRole('button', { name: '导入…', exact: true }).click()
    await expect(create.getByRole('button', { name: '导入…', exact: true })).toBeEnabled()
    await expect(create).toBeVisible()
    await expect(page.locator('.vm-settings-navigation [data-drive-id]')).toHaveCount(3)
    await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }) }, base)
    await create.getByRole('button', { name: '导入…', exact: true }).click()
    await nav.getByRole('button', { name: 'IDE 磁盘 1 的操作', exact: true }).click()
    await page.getByRole('menuitem', { name: '下移', exact: true }).click()
    await expect(nav.locator('[data-drive-id]').nth(1)).toHaveAccessibleName('USB 光驱 1')
    await nav.getByRole('button', { name: 'VirtIO 磁盘 2', exact: true }).click()
    await page.waitForTimeout(2200)
    await page.screenshot({ path: 'test-results/utm-drive-details.png', animations: 'disabled' })
    await settings.getByRole('button', { name: '保存', exact: true }).click()
    await expect(settings).toHaveCount(0)
    const saved = await data()
    expect(saved.settings.drives?.map(drive => drive.interface)).toEqual(['virtio', 'usb', 'ide', 'virtio'])
    expect(Object.keys(saved.managed_disks!)).toHaveLength(3)
    for (const info of Object.values(saved.managed_disks!)) if (info.path) await access(info.path)
    expect(Object.values(saved.managed_disks!).map(info => info.format)).toEqual(['raw', 'qcow2', 'qcow2'])
    expect(await readFile(base)).toEqual(original)
    expect(await readFile(iso, 'utf8')).toBe('external ISO')
    await open()
    for (let index = 0; index < 5; index++) { await newDrive(); await create.getByRole('checkbox', { name: '可移动介质' }).check(); await create.getByRole('button', { name: '创建', exact: true }).click() }
    await expect(nav.getByRole('button', { name: '新建驱动器', exact: true })).toBeDisabled()
    await settings.getByRole('button', { name: '取消', exact: true }).click()
    await page.getByRole('button', { name: '丢弃修改', exact: true }).click()
    expect((await data()).settings.drives).toHaveLength(4)
    await page.getByRole('button', { name: '启动', exact: true }).click()
    await expect(page.getByText('仅查看', { exact: true })).toBeVisible({ timeout: 20000 })
    await open()
    await expect(nav.getByRole('button', { name: '新建驱动器', exact: true })).toBeDisabled()
    await nav.getByRole('button', { name: 'IDE 磁盘 1', exact: true }).click()
    await expect(settings.getByRole('button', { name: '删除驱动器…', exact: true })).toBeDisabled()
  } finally {
    await app.evaluate(({ app }) => app.exit(0)).catch(() => undefined)
    await app.close().catch(() => undefined)
    execFileSync(uv, ['run', 'python', '-m', 'palette.cli', '--root', root, 'daemon', 'stop'], { cwd: repository })
    if (!resolve(root).startsWith(join(tmpdir(), 'palette-devices-'))) throw new Error('Unexpected cleanup root')
    await rm(root, { recursive: true, force: true, maxRetries: 20, retryDelay: 250 })
  }
})
