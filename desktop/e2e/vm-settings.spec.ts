import { test, expect, _electron as electron } from '@playwright/test'
import { mkdtemp, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { execFileSync } from 'node:child_process'

test('VM settings persist hardware, expand storage, protect running VMs and negotiate old owners', async () => {
  test.setTimeout(120_000)
  const repository = resolve('..')
  const root = await mkdtemp(join(tmpdir(), 'palette-settings-'))
  const uv = process.env.PALETTE_UV ?? 'uv'
  execFileSync(uv, ['run', 'python', resolve('scripts/setup_fixture.py'), root], { cwd: repository })
  const application = await electron.launch({ args: [resolve('out/main/index.js')], env: { ...process.env, PALETTE_ROOT: root, PALETTE_UV: uv } })
  try {
    const page = await application.firstWindow()
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    async function screenshot(path: string): Promise<void> {
      await page.evaluate(async () => { await Promise.all(document.getAnimations().filter(animation => animation.effect?.getTiming().iterations !== Infinity).map(animation => animation.finished.catch(() => {}))) })
      await page.screenshot({ path })
    }
    await expect(page.getByText('后台已连接')).toBeVisible({ timeout: 30000 })
    const vmId = await page.evaluate(async path => {
      const result = await window.palette.request('vms.create', undefined, { name: '配置测试', profile_id: 'default', source: 'image', path, vcpus: 1, memory_mib: 512, disk_gib: 24, network: 'offline' }) as { vm_id: string }
      return result.vm_id
    }, join(root, 'base.qcow2'))
    await expect(page.getByRole('button', { name: '配置测试', exact: true })).toBeVisible({ timeout: 10000 })
    await page.getByRole('button', { name: '虚拟机管理', exact: true }).click()
    const managementRow = page.locator('tbody tr').filter({ has: page.getByRole('button', { name: '配置测试', exact: true }) })
    await managementRow.getByRole('button', { name: '虚拟机设置', exact: true }).click()
    const settings = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: '虚拟机设置', exact: true }) })
    const selectSetting = async (name: string, choice: string) => {
      const trigger = settings.getByRole('combobox', { name, exact: true })
      await trigger.click()
      await page.getByRole('option', { name: choice, exact: true }).click()
      await expect(trigger).toHaveText(choice)
    }
    await expect(settings.getByLabel('名称', { exact: true })).toHaveValue('配置测试')
    await settings.getByRole('button', { name: '启动', exact: true }).click()
    await settings.getByRole('combobox', { name: '启动顺序', exact: true }).click()
    await expect(page.getByRole('option', { name: '光盘优先', exact: true })).toBeDisabled()
    await page.keyboard.press('Escape')
    await writeFile(join(root, 'install.iso'), 'Disposable installation media for selector coverage')
    await application.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }) }, join(root, 'install.iso'))
    await settings.getByRole('button', { name: '新建驱动器', exact: true }).click()
    const createDrive = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: '新建驱动器', exact: true }) })
    await createDrive.getByRole('checkbox', { name: '可移动介质' }).check()
    await createDrive.getByRole('button', { name: '创建', exact: true }).click()
    await settings.getByRole('button', { name: '浏览…', exact: true }).click()
    await expect(settings.getByRole('combobox', { name: '连接状态', exact: true })).toHaveText('连接介质')
    await settings.getByRole('button', { name: '启动', exact: true }).click()
    await selectSetting('启动顺序', '光盘优先')
    await selectSetting('启动光驱', 'USB 光驱 1')
    await settings.getByRole('button', { name: 'USB 光驱 1', exact: true }).click()
    await selectSetting('连接状态', '弹出介质')
    await settings.getByRole('button', { name: '启动', exact: true }).click()
    await expect(settings.getByRole('combobox', { name: '启动顺序', exact: true })).toHaveText('自动')
    await settings.getByRole('combobox', { name: '启动顺序', exact: true }).click()
    await expect(page.getByRole('option', { name: '光盘优先', exact: true })).toBeDisabled()
    await screenshot('test-results/vm-settings-disabled-option.png')
    await page.keyboard.press('Escape')
    await settings.getByRole('button', { name: '处理器与内存', exact: true }).click()
    await settings.getByLabel('CPU 核数').fill('1.5')
    await settings.getByRole('button', { name: '保存', exact: true }).click()
    await expect(settings.getByRole('alert')).toContainText('整数')
    await settings.getByRole('alert').getByRole('button', { name: '复制调试信息', exact: true }).click()
    await expect(settings.getByRole('alert')).toContainText('已复制')
    expect(JSON.parse(await application.evaluate(({ clipboard }) => clipboard.readText()))).toMatchObject({ source: 'application', vmId, error: expect.stringContaining('整数') })
    await settings.getByLabel('CPU 核数').fill('2')
    await settings.getByLabel('内存 / GiB').fill('1')
    await settings.getByRole('button', { name: '显示', exact: true }).click()
    await settings.getByRole('combobox', { name: '虚拟显卡', exact: true }).click()
    await expect(page.getByRole('option', { name: '标准 VGA', exact: true })).toHaveAttribute('aria-selected', 'true')
    await page.keyboard.press('Escape')
    await selectSetting('默认分辨率', '指定启动分辨率')
    await selectSetting('分辨率预设', '自定义')
    await selectSetting('分辨率预设', '1920 × 1080')
    await expect(settings.getByLabel('宽度 / px')).toHaveValue('1920')
    await expect(settings.getByLabel('高度 / px')).toHaveValue('1080')
    await settings.getByRole('button', { name: '网络', exact: true }).click()
    await selectSetting('网络模式', 'NAT')
    await selectSetting('虚拟网卡', 'VirtIO 网络')
    await settings.getByLabel('MAC 地址').fill('52:54:00:11:22:33')
    await settings.getByRole('button', { name: '添加', exact: true }).click()
    await selectSetting('协议', 'UDP')
    await settings.getByLabel('宿主端口').fill('8085')
    await settings.getByLabel('客户机端口').fill('85')
    await screenshot('test-results/vm-settings-network.png')
    await application.evaluate(({ BrowserWindow }) => { const window = BrowserWindow.getAllWindows()[0]; if (window.isMinimized()) window.restore(); window.show(); window.focus(); window.setContentSize(1100, 700) })
    await expect.poll(() => page.evaluate(() => [window.innerWidth, window.innerHeight]), { timeout: 10000 }).toEqual([1100, 700])
    const saveBounds = await settings.getByRole('button', { name: '保存', exact: true }).boundingBox()
    expect(saveBounds).not.toBeNull()
    expect(saveBounds!.y + saveBounds!.height).toBeLessThanOrEqual(700)
    await screenshot('test-results/vm-settings-960.png')
    await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1440, 900))
    await settings.getByRole('button', { name: '声音', exact: true }).click()
    await selectSetting('声音输出', '启用声音')
    await settings.getByRole('button', { name: '保存', exact: true }).click()
    await expect(settings).toBeHidden()
    await managementRow.getByRole('button', { name: '虚拟机设置', exact: true }).click()
    await settings.getByRole('button', { name: '处理器与内存', exact: true }).click()
    await expect(settings.getByLabel('CPU 核数')).toHaveValue('2')
    await expect(settings.getByLabel('内存 / GiB')).toHaveValue('1')
    await settings.getByRole('button', { name: '显示', exact: true }).click()
    await expect(settings.getByRole('combobox', { name: '默认分辨率', exact: true })).toHaveText('指定启动分辨率')
    await expect(settings.getByRole('combobox', { name: '分辨率预设', exact: true })).toHaveText('1920 × 1080')
    await settings.getByRole('button', { name: '网络', exact: true }).click()
    await expect(settings.getByRole('combobox', { name: '网络模式', exact: true })).toHaveText('NAT')
    await expect(settings.getByRole('combobox', { name: '虚拟网卡', exact: true })).toHaveText('VirtIO 网络')
    await expect(settings.getByRole('combobox', { name: '协议', exact: true })).toHaveText('UDP')
    await expect(settings.getByLabel('宿主端口')).toHaveValue('8085')
    await expect(settings.getByLabel('客户机端口')).toHaveValue('85')
    await settings.getByRole('combobox', { name: '虚拟网卡', exact: true }).click()
    await expect(page.getByRole('option', { name: 'VirtIO 网络', exact: true })).toHaveAttribute('aria-selected', 'true')
    await page.keyboard.press('Escape')
    await expect(settings.getByRole('button', { name: '保存', exact: true })).toBeDisabled()
    await settings.getByRole('button', { name: '常规', exact: true }).click()
    await settings.getByLabel('名称', { exact: true }).fill('未保存名称')
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: '继续编辑', exact: true }).click()
    await expect(settings.getByLabel('名称', { exact: true })).toHaveValue('未保存名称')
    await settings.getByRole('button', { name: '取消', exact: true }).click()
    await page.getByRole('button', { name: '丢弃修改', exact: true }).click()
    await managementRow.getByRole('button', { name: '虚拟机设置', exact: true }).click()
    await settings.getByRole('button', { name: 'VirtIO 磁盘 1', exact: true }).click()
    await settings.getByRole('button', { name: '扩容磁盘', exact: true }).click()
    await page.getByLabel('目标容量 / GiB').fill('32')
    await page.getByRole('button', { name: '确认扩容', exact: true }).click()
    await expect(settings.getByRole('status')).toContainText('磁盘已扩容')
    await screenshot('test-results/vm-settings-storage.png')
    await settings.getByRole('button', { name: '取消', exact: true }).click()
    await page.getByRole('button', { name: '虚拟机管理', exact: true }).click()
    await page.locator('tbody').getByRole('button', { name: '配置测试', exact: true }).click()
    await page.getByRole('button', { name: '启动', exact: true }).click()
    await expect(page.getByText('仅查看', { exact: true })).toBeVisible({ timeout: 20000 })
    await page.getByRole('button', { name: '虚拟机设置', exact: true }).click()
    await settings.getByRole('button', { name: '处理器与内存', exact: true }).click()
    await expect(settings.getByLabel('CPU 核数')).toBeDisabled()
    await expect(settings.getByRole('button', { name: '保存', exact: true })).toBeDisabled()
    await settings.getByRole('button', { name: '网络', exact: true }).click()
    await expect(settings.getByRole('combobox', { name: '网络模式', exact: true })).toBeDisabled()
    await expect(settings.getByRole('combobox', { name: '虚拟网卡', exact: true })).toBeDisabled()
    await expect(settings.getByRole('combobox', { name: '协议', exact: true })).toBeDisabled()
    await screenshot('test-results/vm-settings-readonly.png')
    await settings.getByRole('button', { name: '关闭', exact: true }).first().click()
    await page.locator('.desktop-main').getByRole('button', { name: '配置测试 的操作' }).click()
    await page.getByRole('menuitem', { name: '关机', exact: true }).click()
    await page.getByRole('dialog', { name: '强制停止虚拟机', exact: true }).getByRole('button', { name: '确认', exact: true }).click()
    await expect(page.getByRole('button', { name: '启动', exact: true })).toBeVisible({ timeout: 10000 })
    const data = await page.evaluate(async vmId => await window.palette.request('vms.settings.get', vmId) as { disk: { virtual_bytes: number }; settings: { audio_enabled: boolean } }, vmId)
    expect(data.disk.virtual_bytes).toBe(32 * 1024 ** 3)
    expect(data.settings.audio_enabled).toBe(true)
    const oldOwner = await page.evaluate(async () => { const current = await window.palette.connect(); return { ...current, features: current.features.filter(feature => feature !== 'vm-drives-v1') } })
    await application.evaluate(({ ipcMain }, owner) => { ipcMain.removeHandler('connect'); ipcMain.handle('connect', async () => owner) }, oldOwner)
    await page.getByRole('button', { name: '设置', exact: true }).click()
    await page.getByRole('button', { name: '重新连接', exact: true }).click()
    await page.getByRole('button', { name: '虚拟机管理', exact: true }).click()
    await page.locator('tbody').getByRole('button', { name: '配置测试', exact: true }).click()
    await page.getByRole('button', { name: '虚拟机设置', exact: true }).click()
    await expect(settings.getByRole('status')).toContainText('当前后台需要升级')
    expect(await page.locator('body').innerText()).not.toMatch(/prompt|Cashmere|Electron|TypeScript|设计系统/i)
    expect(errors).toEqual([])
  } finally {
    await application.evaluate(({ app }) => app.exit(0)).catch(() => {})
    await application.close().catch(() => {})
    try { execFileSync(uv, ['run', 'palette', '--root', root, 'daemon', 'stop'], { cwd: repository }) } catch { /* The test owner may already be stopped. */ }
    await rm(root, { recursive: true, force: true, maxRetries: 20, retryDelay: 250 })
  }
})
