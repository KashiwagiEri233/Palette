import { test, expect, _electron as electron } from '@playwright/test'
import { mkdtemp, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { execFileSync } from 'node:child_process'

test('VM settings persist hardware, expand storage, protect running VMs and negotiate old owners', async () => {
  const repository = resolve('..')
  const root = await mkdtemp(join(tmpdir(), 'palette-settings-'))
  const uv = process.env.PALETTE_UV ?? 'uv'
  execFileSync(uv, ['run', 'python', resolve('scripts/setup_fixture.py'), root], { cwd: repository })
  const application = await electron.launch({ args: [resolve('out/main/index.js')], env: { ...process.env, PALETTE_ROOT: root, PALETTE_UV: uv } })
  try {
    const page = await application.firstWindow()
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    async function screenshot(path: string): Promise<void> {
      await page.evaluate(async () => { await Promise.all(document.getAnimations().filter(animation => animation.effect?.getTiming().iterations !== Infinity).map(animation => animation.finished.catch(() => {}))) })
      await page.screenshot({ path })
    }
    await expect(page.getByText('后台已连接')).toBeVisible({ timeout: 30000 })
    const vmId = await page.evaluate(async path => {
      const result = await window.palette.request('vms.create', undefined, { name: '配置测试', profile_id: 'default', source: 'image', path, vcpus: 1, memory_mib: 512, disk_gib: 24, network: 'offline' }) as { vm_id: string }
      return result.vm_id
    }, join(root, 'base.qcow2'))
    await expect(page.getByRole('button', { name: '配置测试', exact: true }).first()).toBeVisible({ timeout: 10000 })
    await page.getByLabel('配置测试 的操作').selectOption('settings')
    const settings = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: '虚拟机设置', exact: true }) })
    await expect(settings.getByLabel('名称', { exact: true })).toHaveValue('配置测试')
    await settings.getByRole('button', { name: '处理器与内存', exact: true }).click()
    await settings.getByLabel('CPU 核数').fill('1.5')
    await settings.getByRole('button', { name: '保存', exact: true }).click()
    await expect(settings.getByRole('alert')).toContainText('整数')
    await settings.getByLabel('CPU 核数').fill('2')
    await settings.getByLabel('内存 / GiB').fill('1')
    await settings.getByRole('button', { name: '显示', exact: true }).click()
    await settings.getByLabel('默认分辨率', { exact: true }).selectOption('custom')
    await settings.getByLabel('分辨率预设').selectOption('custom')
    await expect(settings.getByLabel('分辨率预设')).toHaveValue('custom')
    await settings.getByLabel('分辨率预设').selectOption('1920x1080')
    await settings.getByRole('button', { name: '网络', exact: true }).click()
    await settings.getByLabel('网络模式').selectOption('nat')
    await settings.getByLabel('虚拟网卡').selectOption('virtio-net-pci')
    await settings.getByLabel('MAC 地址').fill('52:54:00:11:22:33')
    await settings.getByRole('button', { name: '添加', exact: true }).click()
    await settings.getByLabel('宿主端口').fill('8085')
    await settings.getByLabel('客户机端口').fill('85')
    await screenshot('test-results/vm-settings-network.png')
    await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(960, 640))
    await page.waitForFunction(() => window.innerWidth === 960 && window.innerHeight === 640)
    const saveBounds = await settings.getByRole('button', { name: '保存', exact: true }).boundingBox()
    expect(saveBounds).not.toBeNull()
    expect(saveBounds!.y + saveBounds!.height).toBeLessThanOrEqual(640)
    await screenshot('test-results/vm-settings-960.png')
    await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1440, 900))
    await settings.getByRole('button', { name: '声音', exact: true }).click()
    await settings.getByLabel('声音输出').selectOption('enabled')
    await settings.getByRole('button', { name: '保存', exact: true }).click()
    await expect(settings).toBeHidden()
    await page.getByLabel('配置测试 的操作').selectOption('settings')
    await settings.getByRole('button', { name: '处理器与内存', exact: true }).click()
    await expect(settings.getByLabel('CPU 核数')).toHaveValue('2')
    await expect(settings.getByLabel('内存 / GiB')).toHaveValue('1')
    await settings.getByRole('button', { name: '常规', exact: true }).click()
    await settings.getByLabel('名称', { exact: true }).fill('未保存名称')
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: '继续编辑', exact: true }).click()
    await expect(settings.getByLabel('名称', { exact: true })).toHaveValue('未保存名称')
    await settings.getByRole('button', { name: '取消', exact: true }).click()
    await page.getByRole('button', { name: '丢弃修改', exact: true }).click()
    await page.getByLabel('配置测试 的操作').selectOption('settings')
    await settings.getByRole('button', { name: '磁盘与启动', exact: true }).click()
    await settings.getByRole('button', { name: '扩容磁盘', exact: true }).click()
    await page.getByLabel('目标容量 / GiB').fill('32')
    await page.getByRole('button', { name: '确认扩容', exact: true }).click()
    await expect(settings.getByRole('status')).toContainText('磁盘已扩容')
    await screenshot('test-results/vm-settings-storage.png')
    await settings.getByRole('button', { name: '取消', exact: true }).click()
    await page.getByRole('button', { name: '配置测试', exact: true }).first().click()
    await page.getByRole('button', { name: '启动', exact: true }).click()
    await expect(page.getByText('仅查看', { exact: true })).toBeVisible({ timeout: 20000 })
    await page.getByRole('button', { name: '虚拟机设置', exact: true }).click()
    await settings.getByRole('button', { name: '处理器与内存', exact: true }).click()
    await expect(settings.getByLabel('CPU 核数')).toBeDisabled()
    await expect(settings.getByRole('button', { name: '保存', exact: true })).toBeDisabled()
    await screenshot('test-results/vm-settings-readonly.png')
    await settings.getByRole('button', { name: '关闭', exact: true }).first().click()
    await page.getByLabel('配置测试 的操作').selectOption('stop')
    await expect(page.getByRole('button', { name: '启动', exact: true })).toBeVisible({ timeout: 10000 })
    const data = await page.evaluate(async vmId => await window.palette.request('vms.settings.get', vmId) as { disk: { virtual_bytes: number }; settings: { audio_enabled: boolean } }, vmId)
    expect(data.disk.virtual_bytes).toBe(32 * 1024 ** 3)
    expect(data.settings.audio_enabled).toBe(true)
    const oldOwner = await page.evaluate(async () => ({ ...await window.palette.connect(), features: [] }))
    await application.evaluate(({ ipcMain }, owner) => { ipcMain.removeHandler('connect'); ipcMain.handle('connect', async () => owner) }, oldOwner)
    await page.getByRole('button', { name: '环境设置', exact: true }).click()
    await page.getByRole('button', { name: '重新连接', exact: true }).click()
    await page.getByRole('button', { name: '配置测试', exact: true }).first().click()
    await page.getByRole('button', { name: '虚拟机设置', exact: true }).click()
    await expect(settings.getByRole('status')).toContainText('当前后台需要升级')
    expect(await page.locator('body').innerText()).not.toMatch(/prompt|Cashmere|Electron|TypeScript|设计系统/i)
    expect(errors).toEqual([])
  } finally {
    await application.evaluate(({ app }) => app.exit(0)).catch(() => {})
    await application.close().catch(() => {})
    try { execFileSync(uv, ['run', 'palette', '--root', root, 'daemon', 'stop'], { cwd: repository }) } catch { /* The test owner may already be stopped. */ }
    await rm(root, { recursive: true, force: true })
  }
})
