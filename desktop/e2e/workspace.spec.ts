import { test, expect, _electron as electron } from '@playwright/test'
import { execFileSync } from 'node:child_process'
import { mkdir, mkdtemp, rm } from 'node:fs/promises'
import { join, resolve } from 'node:path'

test('workspace navigation, persisted drafts, responsive panels, settings and console', async () => {
  test.setTimeout(120_000)
  const repository = resolve('..')
  const temporaryRoot = join(repository, '.runtime', 'desktop-workspace-tests')
  await mkdir(temporaryRoot, { recursive: true })
  const root = await mkdtemp(join(temporaryRoot, 'workspace-'))
  const uv = process.env.PALETTE_UV ?? 'uv'
  execFileSync(uv, ['run', '--offline', 'python', resolve('scripts/setup_fixture.py'), root], { cwd: repository })
  const application = await electron.launch({ args: [`--user-data-dir=${join(root, 'electron')}`, resolve('out/main/index.js')], env: { ...process.env, PALETTE_ROOT: root, PALETTE_UV: uv } })
  try {
    const page = await application.firstWindow()
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await expect(page.getByText('后台已连接', { exact: true })).toBeVisible({ timeout: 30_000 })
    await page.evaluate(async () => { await document.fonts.ready; localStorage.removeItem('palette.layout.v1') })
    await expect(page.getByRole('heading', { name: '想让 Agent 做什么？' })).toBeVisible()
    expect(await page.locator('h1').evaluate(element => getComputedStyle(element).fontFamily)).toContain('Inter')
    expect(await page.locator('body').innerText()).not.toMatch(/prompt|实现方案|内部技术|Electron|TypeScript|Cashmere|TODO|mock/i)
    await page.screenshot({ path: 'test-results/home-refactor.png' })
    const vmId = await page.evaluate(async path => {
      const data = await window.palette.request('vms.create', undefined, { name: '工作区测试', profile_id: 'default', source: 'image', path, vcpus: 1, memory_mib: 512, disk_gib: 24, network: 'offline' }) as { vm_id: string }
      return data.vm_id
    }, join(root, 'base.qcow2'))
    await expect(page.getByRole('button', { name: '工作区测试', exact: true })).toBeVisible({ timeout: 10_000 })
    await page.getByRole('button', { name: '工作区测试', exact: true }).click()
    await page.getByLabel('任务内容').fill('整理下载目录')
    await page.getByRole('button', { name: '保存为新对话' }).click()
    await expect(page.locator('.conversation-title')).toHaveText('整理下载目录')
    await expect(page.locator('.vm-workspace')).toBeVisible()
    await expect(page.getByRole('button', { name: '发送', exact: true })).toBeDisabled()
    await page.getByLabel('任务内容').fill('保留草稿，等待配置模型')
    await expect.poll(async () => page.evaluate(async () => (await window.palette.request('conversations.list', undefined, {})).conversations[0]?.draft)).toBe('保留草稿，等待配置模型')
    await page.screenshot({ path: 'test-results/conversation-refactor.png' })
    await page.keyboard.press('Control+j')
    await expect(page.locator('.vm-workspace')).toBeHidden()
    await page.keyboard.press('Control+j')
    await expect(page.locator('.vm-workspace')).toBeVisible()
    await page.keyboard.press('Control+b')
    await expect(page.locator('.app-sidebar')).toBeHidden()
    await page.keyboard.press('Control+b')
    await expect(page.locator('.app-sidebar')).toBeVisible()
    for (const width of [1280, 1279, 1100]) {
      await application.evaluate(({ BrowserWindow }, width) => BrowserWindow.getAllWindows()[0].setContentSize(width, 800), width)
      await page.waitForFunction(width => innerWidth === width, width)
      await expect(page.locator('.collapsed-vm-navigation')).toHaveCount(width < 1280 ? 1 : 0)
      expect((await page.locator('.vm-workspace').boundingBox())!.width).toBeGreaterThanOrEqual(520)
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    }
    await application.evaluate(({ BrowserWindow }) => { const window = BrowserWindow.getAllWindows()[0]; window.setMinimumSize(600, 640); window.setContentSize(1000, 760) })
    await page.waitForFunction(() => innerWidth === 1000)
    await expect(page.locator('.conversation-page')).toHaveAttribute('data-workspace-mode', 'drawer')
    await page.getByRole('button', { name: '显示工作区' }).click()
    await expect(page.getByRole('dialog', { name: '虚拟机工作区' })).toBeVisible()
    await page.keyboard.press('Escape')
    await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1440, 900))
    await page.waitForFunction(() => innerWidth === 1440)
    await page.getByRole('button', { name: '设置', exact: true }).click()
    await page.getByRole('button', { name: '外观', exact: true }).click()
    await page.getByRole('button', { name: '深色', exact: true }).click()
    await expect(page.locator('html')).toHaveClass(/dark/)
    await expect(page.getByRole('button', { name: '深色', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await page.evaluate(async () => { await Promise.all(document.getAnimations().filter(animation => animation.effect?.getTiming().iterations !== Infinity).map(animation => animation.finished.catch(() => {}))); await new Promise(requestAnimationFrame); await new Promise(requestAnimationFrame) })
    await page.screenshot({ path: 'test-results/settings-dark-refactor.png' })
    await page.getByRole('button', { name: '浅色', exact: true }).click()
    await page.getByRole('button', { name: '虚拟机管理', exact: true }).click()
    await page.locator('tbody').getByRole('button', { name: '工作区测试', exact: true }).click()
    await page.getByRole('button', { name: '启动', exact: true }).filter({ visible: true }).last().click()
    await expect(page.getByText('仅查看', { exact: true })).toBeVisible({ timeout: 20_000 })
    await expect(page.locator('.rfb-mount canvas')).toBeVisible()
    await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].focus())
    await expect.poll(() => page.evaluate(() => document.hasFocus())).toBe(true)
    await page.getByRole('button', { name: '接管', exact: true }).click()
    await expect(page.getByText('人工控制', { exact: true })).toBeVisible()
    await page.keyboard.press('Control+Alt')
    await expect(page.getByText('仅查看', { exact: true })).toBeVisible()
    await page.keyboard.press('Control+k')
    await page.getByRole('combobox').fill('整理下载目录')
    await page.getByRole('option', { name: /整理下载目录/ }).click()
    await expect(page.getByLabel('任务内容')).toHaveValue('保留草稿，等待配置模型')
    await page.locator('.conversation-title').click()
    await page.getByRole('textbox', { name: '对话标题', exact: true }).fill('整理下载目录（待办）')
    await page.getByRole('button', { name: '保存', exact: true }).click()
    await expect(page.locator('.conversation-title')).toHaveText('整理下载目录（待办）')
    await page.locator('.vm-conversations .conversation-row-wrap').click({ button: 'right' })
    await page.getByRole('menuitem', { name: '置顶', exact: true }).click()
    await expect.poll(async () => page.evaluate(async () => (await window.palette.request('conversations.list', undefined, {})).conversations[0].pinned)).toBe(true)
    await page.reload()
    await expect(page.getByText('后台已连接', { exact: true })).toBeVisible({ timeout: 30_000 })
    await expect(page.locator('.conversation-row-wrap').first()).toContainText('整理下载目录')
    expect((await page.evaluate(async () => window.palette.request('conversations.list', undefined, {}))).conversations[0].vm_id).toBe(vmId)
    expect(errors).toEqual([])
  } finally {
    await application.evaluate(({ app }) => app.exit(0)).catch(() => {})
    await application.close().catch(() => {})
    try { execFileSync(uv, ['run', '--offline', 'palette', '--root', root, 'daemon', 'stop'], { cwd: repository }) } catch { /* Owner may already be stopped. */ }
    if (!resolve(root).startsWith(join(temporaryRoot, 'workspace-'))) throw new Error('Unexpected cleanup root')
    await rm(root, { recursive: true, force: true, maxRetries: 20, retryDelay: 250 })
  }
})
