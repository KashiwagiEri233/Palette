import { test, expect, _electron as electron } from '@playwright/test'
import { createServer } from 'node:http'
import { execFileSync } from 'node:child_process'
import { mkdir, mkdtemp, rm } from 'node:fs/promises'
import { join, resolve } from 'node:path'

test('manages multiple custom providers, imports models and only offers configured models', async () => {
  test.setTimeout(180000)
  const repository = resolve('..')
  const temporary = join(repository, '.runtime', 'desktop-provider-tests')
  await mkdir(temporary, { recursive: true })
  const root = await mkdtemp(join(temporary, 'providers-'))
  const uv = process.env.PALETTE_UV ?? 'uv'
  execFileSync(uv, ['run', '--offline', 'python', resolve('scripts/setup_fixture.py'), root], { cwd: repository })
  let failDiscovery = false
  const server = createServer((request, response) => {
    expect(request.headers.authorization).toBe('Bearer first-key')
    response.writeHead(failDiscovery ? 401 : 200, { 'content-type': 'application/json' })
    response.end(JSON.stringify(failDiscovery ? { error: 'first-key invalid' } : { data: [{ id: 'shared-id', name: 'Shared' }, { id: 'unselected-id', name: 'Unselected' }] }))
  })
  await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve))
  const endpoint = `http://127.0.0.1:${(server.address() as { port: number }).port}/v1`
  const launch = () => electron.launch({ args: [`--user-data-dir=${join(root, 'electron')}`, resolve('out/main/index.js')], env: { ...process.env, PALETTE_ROOT: root, PALETTE_UV: uv } })
  let application = await launch()
  try {
    let page = await application.firstWindow()
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await expect(page.getByText('后台已连接', { exact: true })).toBeVisible({ timeout: 30000 })
    // Bulk provider saves have their own bounded IPC allowance above 64 KiB.
    const batch = await page.evaluate(async baseUrl => {
      const provider = { id: 'custom-ipc-batch', name: 'Batch', api: 'openai-completions' as const, baseUrl, models: Array.from({ length: 200 }, (_, index) => ({ id: `model-${index}-${'a'.repeat(200)}`, name: 'b'.repeat(250), contextWindow: 128000, maxTokens: 8192, vision: false, reasoning: false })) }
      const bytes = new TextEncoder().encode(JSON.stringify({ provider })).length
      const saved = await window.palette.request('agent.providers.save', undefined, { provider })
      const count = saved.providers.find(item => item.id === provider.id)!.modelCount
      await window.palette.request('agent.providers.delete', undefined, { providerId: provider.id })
      return { bytes, count }
    }, endpoint)
    expect(batch.bytes).toBeGreaterThan(64 * 1024)
    expect(batch.count).toBe(200)
    await page.evaluate(async path => {
      await window.palette.request('vms.create', undefined, { name: '提供商验证', profile_id: 'default', source: 'image', path, vcpus: 1, memory_mib: 512, disk_gib: 24, network: 'offline' })
    }, join(root, 'base.qcow2'))
    await page.getByRole('button', { name: '提供商验证', exact: true }).click()
    await page.getByRole('textbox', { name: '任务内容' }).fill('多提供商草稿')
    await page.getByRole('button', { name: '保存为新对话', exact: true }).click()
    const modelSelect = () => page.getByRole('button', { name: '选择模型', exact: true })
    await modelSelect().click()
    await expect(page.getByText('尚未配置可用模型', { exact: true })).toBeVisible()
    await page.getByRole('dialog', { name: '模型与推理等级' }).getByRole('button', { name: '前往设置', exact: true }).click()
    const openSettings = async () => {
      await page.getByRole('button', { name: '设置', exact: true }).click()
      await page.getByRole('button', { name: 'Agent', exact: true }).click()
    }
    const openChat = async () => {
      await page.getByRole('button', { name: '主页', exact: true }).click()
      await page.getByRole('button', { name: '多提供商草稿', exact: true }).click()
    }
    const newCustom = async (name: string, key: string) => {
      await page.getByRole('button', { name: '添加提供商', exact: true }).click()
      await page.getByRole('tab', { name: '自定义 API', exact: true }).click()
      await page.getByLabel('提供商名称', { exact: true }).fill(name)
      await page.getByLabel('Base URL', { exact: true }).fill(endpoint)
      if (key) await page.getByLabel('API Key', { exact: true }).fill(key)
    }
    await newCustom('First service', 'first-key')
    await page.getByRole('button', { name: '获取模型', exact: true }).click()
    let discovery = page.getByRole('dialog', { name: '选择要添加的模型', exact: true })
    await expect(discovery.getByRole('checkbox')).toHaveCount(2)
    await discovery.getByRole('checkbox', { name: 'Shared', exact: true }).click()
    await page.screenshot({ path: 'test-results/provider-model-import.png', animations: 'disabled' })
    await discovery.getByRole('button', { name: '添加所选模型', exact: true }).click()
    const shared = page.locator('.agent-model-editor').filter({ hasText: 'Shared' })
    await shared.locator('summary').first().click()
    await shared.getByText('高级设置', { exact: true }).click()
    await shared.getByRole('switch', { name: '支持推理强度', exact: true }).click()
    await page.getByRole('button', { name: '手动添加模型', exact: true }).click()
    const manual = page.locator('.agent-model-editor').last()
    await manual.getByLabel('模型 ID', { exact: true }).fill('manual-id')
    await manual.getByLabel('显示名称', { exact: true }).fill('Manual')
    await page.getByRole('button', { name: '保存提供商', exact: true }).click()
    await expect(page.getByRole('button', { name: '编辑 First service', exact: true })).toBeVisible()
    await newCustom('Second service', '')
    await page.getByRole('button', { name: '手动添加模型', exact: true }).click()
    await page.getByLabel('模型 ID', { exact: true }).fill('shared-id')
    await page.getByLabel('显示名称', { exact: true }).fill('Another Shared')
    await page.getByRole('button', { name: '保存提供商', exact: true }).click()
    await expect(page.getByRole('button', { name: '编辑 Second service', exact: true })).toBeVisible()
    await page.screenshot({ path: 'test-results/agent-providers-settings.png', animations: 'disabled' })
    await page.evaluate(() => document.documentElement.classList.add('dark'))
    await page.screenshot({ path: 'test-results/agent-providers-settings-dark.png', animations: 'disabled' })
    await page.evaluate(() => document.documentElement.classList.remove('dark'))
    await page.getByRole('button', { name: '编辑 First service', exact: true }).click()
    await expect(page.getByLabel('API Key', { exact: true })).toHaveValue('')
    await page.getByRole('button', { name: '获取模型', exact: true }).click()
    discovery = page.getByRole('dialog', { name: '选择要添加的模型', exact: true })
    await expect(discovery.getByRole('checkbox', { name: 'Shared', exact: true })).toBeChecked()
    await discovery.getByRole('button', { name: '添加所选模型', exact: true }).click()
    await expect(page.locator('.agent-model-editor')).toHaveCount(2)
    failDiscovery = true
    await page.getByRole('button', { name: '获取模型', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('认证失败')
    await expect(page.getByRole('alert')).not.toContainText('first-key')
    await expect(page.locator('.agent-model-editor')).toHaveCount(2)
    await page.getByRole('button', { name: '保存提供商', exact: true }).click()
    await expect(page.locator('.agent-provider-editor')).toHaveCount(0)
    await openChat()
    const openModels = async () => {
      await modelSelect().click()
      await page.getByRole('dialog', { name: '模型与推理等级', exact: true }).getByRole('button', { name: /^模型 / }).click()
      return page.getByRole('dialog', { name: '选择提供商和模型', exact: true })
    }
    let models = await openModels()
    await expect(models.getByRole('group', { name: 'First service', exact: true })).toBeVisible()
    await expect(models.getByRole('group', { name: 'Second service', exact: true })).toHaveCount(0)
    await expect(models.getByRole('group', { name: 'openai', exact: true })).toHaveCount(0)
    await expect(models.getByRole('option')).toHaveCount(2)
    await models.getByRole('option', { name: 'Shared', exact: true }).click()
    await expect(modelSelect()).toContainText('Shared')
    await modelSelect().click()
    await page.getByRole('dialog', { name: '模型与推理等级', exact: true }).getByRole('button', { name: /^推理等级/ }).click()
    await page.keyboard.press('End')
    await page.keyboard.press('Enter')
    await expect(modelSelect()).toContainText('Max')
    await openSettings()
    await page.getByRole('button', { name: '编辑 Second service', exact: true }).click()
    await page.getByLabel('API Key', { exact: true }).fill('second-key')
    await page.getByRole('button', { name: '保存提供商', exact: true }).click()
    await expect(page.locator('.agent-provider-editor')).toHaveCount(0)
    await openChat()
    models = await openModels()
    await expect(models.getByRole('group', { name: 'Second service', exact: true })).toBeVisible()
    await page.screenshot({ path: 'test-results/agent-providers-chat.png', animations: 'disabled' })
    await models.getByRole('option', { name: 'Another Shared', exact: true }).click()
    await expect(modelSelect()).toContainText('Another Shared')
    await openSettings()
    await page.getByRole('button', { name: '编辑 Second service', exact: true }).click()
    await page.locator('.agent-model-editor > summary').click()
    await page.getByRole('button', { name: '移除模型 Another Shared', exact: true }).click()
    await page.getByRole('button', { name: '保存提供商', exact: true }).click()
    await expect(page.locator('.agent-provider-editor')).toHaveCount(0)
    await openChat()
    await expect(modelSelect()).toHaveText('选择模型')
    await expect(page.getByRole('button', { name: '发送', exact: true })).toBeDisabled()
    await expect(page.getByRole('textbox', { name: '任务内容' })).toHaveValue('多提供商草稿')
    models = await openModels()
    await models.getByRole('option', { name: 'Shared', exact: true }).click()
    await openSettings()
    await page.getByRole('button', { name: '删除 First service', exact: true }).click()
    await page.getByRole('dialog', { name: '删除提供商', exact: true }).getByRole('button', { name: '删除提供商', exact: true }).click()
    await expect(page.getByRole('button', { name: '编辑 First service', exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: '编辑 Second service', exact: true }).click()
    await page.getByRole('button', { name: '手动添加模型', exact: true }).click()
    await page.getByLabel('模型 ID', { exact: true }).fill('shared-id')
    await page.getByLabel('显示名称', { exact: true }).fill('Restored Shared')
    const originalSize = await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].getContentSize())
    await application.evaluate(({ BrowserWindow }) => { const window = BrowserWindow.getAllWindows()[0]; window.setMinimumSize(600, 640); window.setContentSize(700, 800) })
    await page.screenshot({ path: 'test-results/agent-providers-editor-narrow.png', animations: 'disabled' })
    await application.evaluate(({ BrowserWindow }, size) => BrowserWindow.getAllWindows()[0].setContentSize(size[0], size[1]), originalSize)
    await page.getByRole('button', { name: '保存提供商', exact: true }).click()
    await expect(page.locator('.agent-provider-editor')).toHaveCount(0)
    await openChat()
    await expect(modelSelect()).toHaveText('选择模型')
    models = await openModels()
    await models.getByRole('option', { name: 'Restored Shared', exact: true }).click()
    await expect(modelSelect()).toContainText('Restored Shared')
    expect(errors).toEqual([])
    await page.evaluate(() => window.palette.finishClose('background'))
    await application.close()
    application = await launch()
    page = await application.firstWindow()
    await expect(page.getByText('后台已连接', { exact: true })).toBeVisible({ timeout: 30000 })
    await openChat()
    await expect(modelSelect()).toContainText('Restored Shared')
    await expect(page.getByRole('textbox', { name: '任务内容' })).toHaveValue('多提供商草稿')
    await openSettings()
    await page.getByRole('button', { name: '编辑 Second service', exact: true }).click()
    await page.getByRole('button', { name: '移除密钥', exact: true }).click()
    await expect(page.locator('.agent-provider-editor')).toHaveCount(0)
    await expect(page.locator('.agent-provider-card').filter({ hasText: 'Second service' })).toContainText('未配置')
    await openChat()
    await expect(modelSelect()).toHaveText('选择模型')
    await modelSelect().click()
    await expect(page.getByText('尚未配置可用模型', { exact: true })).toBeVisible()
    await page.getByRole('dialog', { name: '模型与推理等级' }).getByRole('button', { name: '前往设置', exact: true }).click()
    await page.getByRole('button', { name: '添加提供商', exact: true }).click()
    await expect(page.getByRole('tab', { name: '内置提供商', exact: true })).toHaveAttribute('aria-selected', 'true')
    await page.getByLabel('API Key', { exact: true }).fill('unused-builtin-key')
    await page.getByRole('button', { name: '保存提供商', exact: true }).click()
    await expect(page.getByRole('button', { name: '编辑 openai', exact: true })).toBeVisible()
    await openChat()
    models = await openModels()
    await expect(models.getByRole('group', { name: 'openai', exact: true })).toBeVisible()
    await page.keyboard.press('Escape')
    await openSettings()
    await page.getByRole('button', { name: '编辑 openai', exact: true }).click()
    await page.getByRole('button', { name: '移除密钥', exact: true }).click()
    await expect(page.locator('.agent-provider-editor')).toHaveCount(0)
    await expect(page.locator('.agent-provider-card').filter({ hasText: 'openai' })).toContainText('未配置')
    await page.evaluate(() => window.palette.finishClose('shutdown'))
  } finally {
    await application.evaluate(({ app }) => app.exit(0)).catch(() => {})
    await application.close().catch(() => {})
    server.closeAllConnections()
    await new Promise<void>(resolve => server.close(() => resolve()))
    try { execFileSync(uv, ['run', '--offline', 'python', '-m', 'palette.cli', '--root', root, 'daemon', 'stop'], { cwd: repository, stdio: 'ignore' }) } catch { /* Already stopped through the UI. */ }
    await rm(root, { recursive: true, force: true, maxRetries: 10, retryDelay: 100 })
  }
})
